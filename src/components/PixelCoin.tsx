export function PixelCoin({
  sym,
  size = 22,
  color = "#f2f2f2",
  dim = "rgba(242,242,242,0.45)",
  glow = true,
  style,
}: {
  sym: string;
  size?: number;
  color?: string;
  dim?: string;
  glow?: boolean;
  style?: CSSProperties;
}) {
  const grid = PIXEL_ICONS[sym];
  if (!grid) {
    return (
      <span
        style={{
          fontFamily: "'JetBrains Mono',monospace",
          fontSize: size * 0.42,
          color,
          letterSpacing: 0.5,
          ...style,
        }}
      >
        {sym.slice(0, 3)}
      </span>
    );
  }
  const rects: ReactElement[] = [];
  for (let y = 0; y < 16; y++) {
    const row = grid[y] || "";
    for (let x = 0; x < 16; x++) {
      const c = row[x];
      if (c === "#")
        rects.push(
          <rect key={`${x},${y}`} x={x} y={y} width={1.02} height={1.02} fill={color} />
        );
      else if (c === "o")
        rects.push(
          <rect key={`${x},${y}`} x={x} y={y} width={1.02} height={1.02} fill={dim} />
        );
    }
  }
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      style={{
        display: "block",
        filter: glow
          ? "drop-shadow(0 0 2px rgba(242,242,242,0.4)) drop-shadow(0 0 4px rgba(242,242,242,0.15))"
          : "none",
        ...style,
      }}
    >
      {rects}
    </svg>
  );
}

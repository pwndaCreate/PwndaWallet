/// The counterparty's M1/M2 public contribution, as we hand it to the engine.
pub struct CounterpartyKeys<'a> {
    pub key_share_point: &'a str,
    pub chain_a_pubkey: &'a str,
    pub adaptor_point: Option<&'a str>,
    pub view_key: Option<&'a str>,
    pub dleq_proof: Option<&'a str>,
    /// The LEADER's committed chain-A slots. Populated only when the
    /// COUNTERPARTY leads (i.e. we follow) — the desk sends them in M1.
    pub t1_slot: Option<i64>,
    pub t2_slot: Option<i64>,
    /// CC-24 / F32-0: the destinations the COUNTERPARTY nominates for its own
    /// chain-A proceeds, taken from M1.
    ///
    /// `None` means "not nominated", and the engine then derives as it always
    /// has — which is both the compatibility path for a desk that has not
    /// shipped this yet and the fallback the desk's own FALSIFY requires.
    /// An empty string is never a destination; `commands::opt_nonempty` is
    /// what turns the wire's `""` into `None`.
    pub claim_dest: Option<&'a str>,
    pub refund_dest: Option<&'a str>,
}


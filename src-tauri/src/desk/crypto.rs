#[derive(Debug, thiserror::Error, PartialEq)]
pub enum CryptoError {
    /// The active provider cannot perform this operation. Carries the reason so
    /// the log names what is missing rather than "failed".
    #[error("desk crypto unavailable: {0}")]
    Unavailable(String),
    #[error("invalid key material: {0}")]
    InvalidMaterial(String),
    #[error("refund broadcast failed: {0}")]
    Broadcast(String),
    /// Raised when mock material reaches a path that moves value.
    #[error(
        "refusing to act on MOCK key material — this swap's keys were generated by the \
         Stage-A placeholder provider, not the real engine. Acting on them cannot recover funds."
    )]
    MockMaterialRefused,

    /// The ENGINE refused the call (`ok:false`, or a typed raise). A
    /// caller/theft-class rejection — a bad point, a pre-sig that does not bind,
    /// an out-of-order call, a guard that fired. **NEVER retried.**
    ///
    /// This variant exists because collapsing it into [`Self::Unavailable`]
    /// would throw away the distinction the transport works hard to preserve:
    /// `Unavailable` invites a retry or a respawn, and retrying a theft-class
    /// rejection is exactly the loop that must not exist.
    #[error("engine rejected {method}: {error_type}: {message}")]
    EngineRejected {
        method: String,
        error_type: String,
        message: String,
    },

    /// The sidecar cannot start with this configuration. Permanent — fix the
    /// config; do NOT respawn.
    #[error("engine sidecar configuration fault: {0}")]
    ConfigFault(String),

    /// C47d: the engine is HEALTHY AND BUSY — the call yielded or timed out
    /// waiting for the one serialized pipe and never reached the child.
    ///
    /// The transport has distinguished this from a hang since C32, and this seam
    /// — whose whole documented purpose is to preserve the transport's
    /// distinctions — was flattening it into [`Self::Unavailable`]. That is how
    /// one `Contended` on `set_lock_b_txid` read as "the engine did not answer"
    /// and killed a funded lane: the caller could not see that retrying was not
    /// just safe but the documented-correct response.
    #[error("engine busy: {method} yielded after {seconds}s without reaching the child")]
    EngineBusy { method: String, seconds: u64 },
}

/// Preserve the transport's error CLASS across the seam.
///
/// Found by running rung 2b's plumbing check: every sidecar failure was being
/// flattened to `Unavailable`, so a permanent engine rejection and a transient
/// death looked identical to callers. The transport distinguishes them
/// deliberately; this conversion is what keeps that distinction alive.
impl From<super::sidecar::SidecarError> for CryptoError {
    fn from(e: super::sidecar::SidecarError) -> Self {
        use super::sidecar::SidecarError as S;
        match e {
            S::EngineRejected {
                method,
                error_type,
                message,
            } => Self::EngineRejected {
                method,
                error_type,
                message,
            },
            S::BadConfig(m) | S::ConfigFault(m) => Self::ConfigFault(m),
            // C47d. Busy is not "did not answer" — the child never SAW the call.
            // Flattened, the one caller with a funded deadline behind it
            // (set_lock_b_txid, 2026-07-28) treated a queue-full moment as an
            // engine failure and died. Preserved, that caller retries.
            S::Contended { method, seconds } => Self::EngineBusy { method, seconds },
            // Spawn / Framing / Timeout / SidecarDied / BadResult are all
            // "the engine did not answer", which is retry-or-respawn territory.
            other => Self::Unavailable(other.to_string()),
        }
    }
}

impl CryptoError {
    /// True when retrying can never help (fix the config, or the engine has
    /// refused on the merits).
    pub fn is_permanent(&self) -> bool {
        matches!(
            self,
            Self::ConfigFault(_)
                | Self::EngineRejected { .. }
                | Self::MockMaterialRefused
                | Self::InvalidMaterial(_)
        )
    }

    /// True when the ENGINE refused on the merits. Never retry these.
    pub fn is_engine_rejection(&self) -> bool {
        matches!(self, Self::EngineRejected { .. })
    }

    /// C47d: true when the engine is healthy and busy — the one error class
    /// where an immediate bounded retry is the documented-correct response
    /// (the transport's own words: tearing down "would kill the work that was
    /// about to finish").
    pub fn is_transient_busy(&self) -> bool {
        matches!(self, Self::EngineBusy { .. })
    }
}

/// Where a swap's key material came from. Persisted with the swap so a refund
/// attempted later can tell whether the material is real.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyProvenance {
    /// Schema-shaped stand-ins. Protocol-conformant, cryptographically inert —
    /// exactly what the Go reference harness puts on the wire.
    Mock,
    /// Produced by the vendored engine library. Safe to act on.
    Vendored,
}

impl KeyProvenance {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Mock => "mock",
            Self::Vendored => "vendored",
        }
    }
    pub fn parse(s: &str) -> Self {
        match s {
            "vendored" => Self::Vendored,
            // Anything unrecognized is treated as mock — the SAFE default,
            // because mock material is refused rather than acted on.
            _ => Self::Mock,
        }
    }
    pub fn is_real(self) -> bool {
        matches!(self, Self::Vendored)
    }
}

/// Everything `init_swap` needs, assembled from the accept RESPONSE.
///
/// It is a context rather than three loose arguments because every field here
/// arrives together, in M1, and using a stale or hand-rolled value is the
/// funds-stranding class: these are the inputs that fix the canonical body.
pub struct SwapInitContext<'a> {
    /// The DESK-assigned swap id. Doubles as the sidecar's handle for this swap.
    pub swap_id: &'a str,
    pub role: ClientRole,
    pub pair: &'a str,
    pub amount_a: &'a str,
    pub amount_b: &'a str,
    pub t0: i64,
    pub t1: i64,
    pub t2: i64,
    /// The chain-A timelock slots FROM M1 — populated only when the DESK leads
    /// (SELL_FOLLOWER). When WE lead they are `None` and the engine derives them
    /// from the live chain tip, which is why the leader path needs chain access
    /// unless a caller supplies them. Never echo the desk's M1 slots when we
    /// lead: in BUY_FOLLOWER they are null by design (v8).
    pub t1_slot: Option<i64>,
    pub t2_slot: Option<i64>,
    /// The NEGOTIATED leader-proof capability — the desk's M1 answer verbatim.
    ///
    /// It belongs in this context for the reason the doc comment above gives:
    /// these are the inputs that fix the canonical body, and this one decides
    /// whether our refund-spend half is an OtVES adaptor or a plain signature.
    /// Taking it from anywhere other than M1 is the funds-stranding class —
    /// `ltc_swap.py:544` refuses to lock chain B when the record says the spend
    /// is plain, so a value that disagrees with the handshake strands the coin
    /// at the worst possible moment rather than failing the handshake.
    pub leader_proof: bool,
    /// The operator's nominated chain-A payout address — the SAME value sent to
    /// the desk in the accept.
    ///
    /// **This must reach OUR engine, because it changes the canonical claim body
    /// on BOTH sides.** `_canonical_claim_body` pays `st.bob.ada_dest`, and the
    /// engine sets that from `payout_address` when present, otherwise deriving
    /// `Address(vkey_hash(B_ada))`. So if the desk applies the nominated address
    /// and we derive, the two parties build DIFFERENT bodies, its claim pre-sig
    /// binds a txid we never construct, and our `adaptor_verify` refuses — which
    /// is exactly what happened to swap `46d85388` once the desk shipped its half
    /// of the D16 wiring (`64ef434`) and ours was still missing.
    ///
    /// The failure is loud and safe — the follower refuses to complete rather than
    /// submitting a claim that pays somewhere it did not intend — but it strands
    /// the swap to T1. Empty is a valid value and means "derive", which is what
    /// both sides did before the wiring existed.
    pub payout_address: &'a str,

    /// The operator's nominated chain-A **refund** address — the same value sent
    /// to the desk in the accept, and the exact mirror of `payout_address` above.
    ///
    /// **It must reach OUR engine for the same reason, one field over.** The
    /// refund body pays `st.alice.ada_dest`. Until the desk's D25 that was derived
    /// unconditionally on both sides, so both agreed and nobody noticed. D25 made
    /// it nominatable and ownership-keyed — which fixed THEIR derivation and left
    /// ours deriving, so the two refund bodies stopped matching and the desk's
    /// refund pre-signature could no longer `adaptor_verify`.
    ///
    /// Caught at M3 on the first drive after their fix, with nothing on chain: we
    /// refuse to submit a lock whose refund we could not complete at T1. That is
    /// the safe direction, and it is still a stranded drive.
    ///
    /// **This is C12 a second time.** Same engine, same class of field, one input
    /// present on one side. The lesson the first instance was supposed to teach is
    /// that a nominatable destination has TWO halves, and shipping either alone
    /// breaks agreement — so when the counterparty makes a value nominatable, that
    /// is the moment to send it, not to note that they did.
    pub refund_address: &'a str,
}

/// Per-swap key material, generated ONCE just after accept.
///
/// The non-custody invariant in type form. Note what is NOT here: the spend
/// scalar. The sidecar mints and keeps it in its OWN encrypted store, addressed
/// by [`engine_ref`](Self::engine_ref) — so the secret never enters Rust at all,
/// and there is no field that could leak into a log, the webview, or the wire.
/// That is stronger than the earlier design, which held the scalar in Rust and
/// relied on `ZeroizeOnDrop` plus discipline to keep it contained.
#[derive(Zeroize, ZeroizeOnDrop)]
pub struct SwapKeyMaterial {
    /// The client's key-share POINT. Sent in M2.
    pub client_key_share_point: String,
    /// The client's chain-A pubkey. Sent in M2 (never in the accept request —
    /// the desk does not read it there; see `DESK-ANSWER-v6.md` Q1).
    pub client_chain_a_pubkey: String,
    /// Adaptor point T. Present only when the CLIENT is the follower
    /// (SELL_FOLLOWER); the desk supplies it in M1 when it follows.
    ///
    /// **CLIENT-1 widens this on the LTC leg:** when we LEAD there with the
    /// leader-proof capability on, we also carry an adaptor point - and it is
    /// READ OUT OF [`dleq_proof`](Self::dleq_proof) by the engine, never
    /// derived beside it. A point supplied next to a proof is a point nobody
    /// proved anything about.
    pub adaptor_point: Option<String>,
    /// CLIENT-1: the cross-group DLEAG proof binding our chain-B share to a
    /// secp256k1 point, when this leg needs one.
    ///
    /// `None` on ADA in BOTH directions - both legs are edwards25519, so there
    /// is no cross-group statement to make and a proof here would signal
    /// cross-curve to the desk. `None` on LTC too unless the swap negotiated
    /// the capability, because an unasked-for proof is refused rather than
    /// ignored.
    pub dleq_proof: Option<String>,
    /// Shared view secret for the XMR/ZEPH joint address. Secret-ish: it grants
    /// visibility, not spend authority. The one allowlisted secret on the wire.
    pub view_key: Option<String>,
    /// Handle to the sidecar's own encrypted state for this swap. The SECRET
    /// lives there, not here.
    pub engine_ref: String,
    /// Chain-A refund timelock slot, committed by the LEADER. Present only when
    /// the CLIENT leads (BUY_FOLLOWER) — the exact mirror of `adaptor_point` /
    /// `view_key`, which are FOLLOWER material. When we follow, the desk
    /// committed the slots in M1 and we leave these `None`. Public, not secret,
    /// so not zeroized.
    #[zeroize(skip)]
    pub t1_slot: Option<i64>,
    /// Chain-A swipe timelock slot. Same leader-only rule as `t1_slot`.
    #[zeroize(skip)]
    pub t2_slot: Option<i64>,
    #[zeroize(skip)]
    pub provenance: KeyProvenance,
}

impl SwapKeyMaterial {
    /// The subset that may legitimately be sent to the desk in M2.
    pub fn keys_request(&self) -> wire::KeysRequest {
        wire::KeysRequest {
            client_key_share_point: self.client_key_share_point.clone(),
            client_chain_a_pubkey: self.client_chain_a_pubkey.clone(),
            adaptor_point: self.adaptor_point.clone(),
            view_key: self.view_key.clone(),
            // CLIENT-1. This was hardcoded `None` with an ADA-shaped reason:
            // "ADA and XMR/ZEPH are both edwards25519 - same curve, no DLEq."
            // True for ADA forever, and wrong for LTC, where chain A is
            // secp256k1 and the cross-group proof is what binds our chain-B
            // share to the point the counterparty encrypts under.
            //
            // The value comes from the ENGINE, which emits it only when this
            // leg needs one and the swap negotiated the capability - so a leg
            // that has no proof still sends `null` here and the ADA wire is
            // byte-identical to what has always settled.
            dleq_proof: self.dleq_proof.clone(),
            // LEADER material: set only when WE lead, so the desk-as-follower can
            // derive the same chain-A script address to watch our lock at.
            t1_slot: self.t1_slot,
            t2_slot: self.t2_slot,
        }
    }
}


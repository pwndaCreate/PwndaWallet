//! The typed boundary the swap-desk cryptography plugs into.
//!
//! # This file is a SEAM, not an implementation
//!
//! The real adaptor-signature and chain-leg cryptography for the ADA<>XMR/ZEPH
//! engine is a vendored Python library (`ed25519_adaptor.py`, `ada_leg.py`,
//! `xmr_leg.py`) that the desk itself does not reimplement — its Go engine
//! adapter bridges to that library over a JSON pipe and, in its own words,
//! "holds no crypto and no chain I/O of its own". Sub-plan 02 is explicit:
//!
//! > Do NOT hand-roll adaptor sigs / DLEq - lift verbatim.
//!
//! That instruction is load-bearing, not stylistic. Both sides of an atomic
//! swap must agree bit-for-bit on nonce derivation, challenge construction and
//! domain separation. A client that differs from the desk by one byte produces
//! a swap that locks real funds and can then neither claim NOR refund — and it
//! would pass every test written alongside it, because the same wrong
//! assumption authors both halves of the comparison. The `-dev` desk runs a
//! stub engine, so even a fully green conformance run proves nothing about
//! cryptographic agreement.
//!
//! So this module defines the OPERATIONS the protocol needs, with their exact
//! wire types from CONTRACT.md, and leaves the construction to whoever supplies
//! a real [`DeskCrypto`]. Everything around it — per-swap keygen at accept
//! time, encrypted persistence, the refund trigger — is real and tested.
//!
//! # Wire-format contract (CONTRACT.md section 2)
//!
//! - ed25519 points / pubkeys: 32 bytes, lowercase hex (64 chars).
//! - Adaptor pre-signature `{rEnc, sp}`: `rEnc` = R_enc 32B hex; `sp` = the
//!   pre-signature scalar reduced mod L, 32-byte **little-endian** hex.
//! - A spend scalar NEVER crosses the wire. Only points, pre-signatures, view
//!   secrets, txids and proofs do.
//!
//! # Swapping in the real provider
//!
//! Implement [`DeskCrypto`] (and [`RefundBroadcaster`]) over the vendored
//! library, return [`KeyProvenance::Vendored`], and change [`active_crypto`].
//! Nothing else in the desk tier needs to move.

#![allow(dead_code)] // the seam is wider than Stage A consumes

use std::time::Duration;
use zeroize::{Zeroize, ZeroizeOnDrop};


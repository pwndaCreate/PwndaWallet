/// The active crypto provider.
///
/// This is an ENUM rather than `&dyn DeskCrypto` on purpose. The vendored
/// provider's operations are `async` (they are round-trips to the sidecar), and
/// async fns are not object-safe: `dyn` would need the `async-trait` crate, and
/// `Cargo.toml` is a permission-gated file here. Enum dispatch costs nothing,
/// keeps the swap-in point explicit, and is honest — there are exactly two
/// providers and there is no plugin story.
pub enum ActiveCrypto {
    /// Schema-shaped stand-ins. Protocol-conformant, cryptographically inert.
    Mock(MockDeskCrypto),
    /// The real vendored engine, driven over the stdio sidecar.
    Vendored(VendoredDeskCrypto),
}

impl ActiveCrypto {
    pub fn provenance(&self) -> KeyProvenance {
        match self {
            Self::Mock(_) => KeyProvenance::Mock,
            Self::Vendored(_) => KeyProvenance::Vendored,
        }
    }

    /// Mint this swap's key material. Runs AFTER accept, keyed on the
    /// desk-assigned swap id (see [`SwapInitContext`]).
    pub async fn generate_swap_keys(
        &self,
        ctx: &SwapInitContext<'_>,
    ) -> Result<SwapKeyMaterial, CryptoError> {
        match self {
            Self::Mock(m) => m.generate_swap_keys(ctx),
            Self::Vendored(v) => v.generate_swap_keys(ctx).await,
        }
    }

    /// Feed the counterparty's half in, forming the 2-of-2 joint key + the lock
    /// addresses. Rejects a torsion/small-order point or a wrong role shape.
    pub async fn ingest_counterparty(
        &self,
        swap_id: &str,
        cp: &CounterpartyKeys<'_>,
    ) -> Result<JointKeys, CryptoError> {
        match self {
            Self::Mock(m) => m.ingest_counterparty(swap_id, cp),
            Self::Vendored(v) => v.ingest_counterparty(swap_id, cp).await,
        }
    }
}

/// The result of an `extract_secret` call, with the `false` case classified.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SecretExtraction {
    pub secret_held: bool,
    pub reason: String,
}

/// Whether the chain-A lock has been spent, and by what.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SpendSighting {
    /// The lock was spent by this transaction. Feed the txid to
    /// [`VendoredDeskCrypto::extract_secret`], which binds it independently.
    Spent { txid: String },
    /// We looked; the lock is still unspent.
    NotSpent,
    /// We could not look. NOT "not spent" — read as that, the whole discovery
    /// path goes quiet at exactly the moment it is needed.
    CouldNotLook { error: String },
}

impl SpendSighting {
    /// Same ordering rule as the lock watcher: a populated `error` wins over
    /// `spent:false`, because that `false` is the fail-soft default rather than
    /// an observation. A `spent:true` with no txid is treated as could-not-look
    /// — there is nothing to hand to `extract_secret`, so claiming a spend was
    /// seen would only produce a confusing failure one step later.
    pub fn from_engine(v: &serde_json::Value) -> Self {
        let err = v.get("error").and_then(|e| e.as_str()).unwrap_or("").trim();
        let spent = v
            .get("spent")
            .and_then(serde_json::Value::as_bool)
            .unwrap_or(false);
        let txid = v
            .get("txid")
            .and_then(|t| t.as_str())
            .unwrap_or("")
            .trim()
            .to_string();

        if !err.is_empty() && !spent {
            return Self::CouldNotLook {
                error: err.to_string(),
            };
        }
        if spent {
            if txid.is_empty() {
                return Self::CouldNotLook {
                    error: "the engine reported the lock spent but named no spending tx".into(),
                };
            }
            return Self::Spent { txid };
        }
        Self::NotSpent
    }
}

/// What a `false` from `extract_secret` actually means.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExtractionOutlook {
    /// The engine holds the scalar. Proceed.
    Held,
    /// Not visible yet, or a transient read failure. Retry the SAME txid.
    RetryLater,
    /// This txid does not carry the swap's secret — a wrong or hostile one.
    /// Permanent **for that txid, not for the swap**: a different transaction
    /// may still be the real refund. So the response is not "give up" and not
    /// "retry this"; it is *keep discovering*.
    ///
    /// This state exists because of engine v11's A5 fix. Before it,
    /// `extract_secret` computed `s - sp`, stored it and reported success
    /// without checking the result was the swap's secret — so any transaction
    /// signed by the same vkey yielded `secretHeld: true` and garbage. The
    /// binding is what makes a wrong txid produce a refusal instead.
    WrongTxid,
    /// This backend can never extract. Retrying is a loop that never ends, and
    /// the coin needs a human.
    Impossible,
    /// C38: the counterparty took chain A via **B3, the after-T2 deep-abort
    /// swipe**, so `s_a` was never published and never will be.
    ///
    /// The script's three branches are `B1 = [sigA, sigB]`, `B2 = [after T1,
    /// sigA, sigB]`, `B3 = [after T2, sigA]`. All three need the leader's
    /// signature and **only B3 omits the follower's**, so a confirmed spend
    /// carrying the leader's vkey witness and not the follower's can only be B3
    /// — one witness where the cooperative paths need two.
    ///
    /// It matters because B3 is signed with an ORDINARY signature, not an
    /// adaptor one, so it leaks nothing. A follower waiting for `s_a` after a
    /// swipe is waiting for something that will never be published.
    ///
    /// **Deliberately NOT folded into [`Impossible`]**, which they superficially
    /// resemble — both mean "stop retrying". They need different humans doing
    /// different things: `Impossible` is a CONFIG fault on our side (a backend
    /// that cannot extract, fix the deployment), while `Swiped` is a PROTOCOL
    /// outcome on the chain (the counterparty deep-aborted; our chain-B coin is
    /// unrecoverable without them volunteering their key share). Collapsing them
    /// would send someone to check their engine config over a coin that is gone.
    Swiped,
}

impl SecretExtraction {
    /// Classify. Anything unrecognized is [`ExtractionOutlook::RetryLater`] —
    /// the safe default, because it neither gives up on a recoverable coin nor
    /// declares an unrecoverable one recovered.
    pub fn outlook(&self) -> ExtractionOutlook {
        if self.secret_held {
            return ExtractionOutlook::Held;
        }
        if self.reason.starts_with("unsupported-backend") {
            return ExtractionOutlook::Impossible;
        }
        // C38 / desk D37. Matched on the engine's own marker literal, which
        // `desk_engine.py:88` defines as `SWIPE_MARKER = "SWIPED (B3"` and builds
        // `SWIPE_REASON` from — so the string is the contract across the language
        // boundary, exactly as the desk pins it with
        // `TestSwipeMarkerMatchesTheEngineLiteral`.
        //
        // Checked BEFORE the fallthrough because the fallthrough is `RetryLater`,
        // and that default — correct for an UNKNOWN reason — is the wrong answer
        // for a KNOWN terminal one. Without this arm we poll forever over a coin
        // that is provably gone, which is the whole of D37.
        if self.reason.contains("SWIPED (B3") {
            return ExtractionOutlook::Swiped;
        }
        // The A5 refusal. Matched on the distinctive phrase rather than the
        // whole sentence so a reworded message still classifies; if it ever
        // stops matching, the fallback is RetryLater, which keeps looking — the
        // safe direction.
        if self.reason.contains("does not carry the swap's secret") {
            return ExtractionOutlook::WrongTxid;
        }
        ExtractionOutlook::RetryLater
    }
}

/// Everything needed to publish a refund, assembled from the persisted record.
pub struct RefundRequest<'a> {
    pub swap_id: &'a str,
    pub pair: &'a str,
    pub direction: &'a str,
    pub refund_address: &'a str,
    /// The pre-signature captured at M3, before the lock.
    pub refund_presig: wire::AdaptorPresig,
    /// Which chain leg the client locked and is reclaiming ("A" or "B").
    pub chain: &'a str,
    pub lock_txid: &'a str,
    pub provenance: KeyProvenance,
}

/// Publishes the refund transaction to the chain the client locked on.
///
/// The future is boxed by hand rather than via `async-trait`, for the same
/// reason [`ActiveCrypto`] is an enum: an `async fn` in a trait is not
/// object-safe, and this trait exists precisely so tests can inject a spy in
/// place of the real broadcaster. Boxing keeps `&dyn RefundBroadcaster` working
/// while the real implementation does chain I/O.
pub type BroadcastFuture<'a> =
    std::pin::Pin<Box<dyn std::future::Future<Output = Result<String, CryptoError>> + Send + 'a>>;

pub trait RefundBroadcaster: Send + Sync {
    fn broadcast_refund<'a>(&'a self, req: &'a RefundRequest<'a>) -> BroadcastFuture<'a>;
}

// ─────────────────────────── Stage-A providers ───────────────────────────

/// Deterministic, schema-shaped stand-ins — the same discipline the Go
/// reference harness uses (`mockHex`). Protocol-conformant and
/// cryptographically INERT: it satisfies the wire format so the state machine,
/// the persistence and the gating can all be exercised end to end, and nothing
/// it produces can move a coin.
pub struct MockDeskCrypto;

/// Stand-in chain-A timelock slots for the mock leader path. Only the ordering
/// (`t2 > t1 > 0`) is load-bearing — that is what the desk's `set_lock_slots`
/// sanity-checks. The real provider derives these from the chain tip inside
/// `init_swap(role=LEADER)`.
/// Timeout for engine calls that REBUILD AND RESCAN a Monero wallet.
///
/// `reclaim` (and the leader's `claim`) go through `restore_joint_and_sweep`:
/// `generate_from_keys` to rebuild the joint wallet, `refresh` to scan stagenet
/// from the restore height, then `sweep_all`. That is minutes of work — the
/// desk's equivalent sweep took 2m3s — against the sidecar's 30s default, so the
/// reclaim could never complete. Observed 2026-07-26: it timed out at 30s twice
/// while the Python side kept scanning, which also desynchronises the sidecar's
/// request/response ids (`expected id 18, got Some(15)`) because the late reply
/// arrives against the next call.
///
/// Deliberately NOT applied to the `watch_*` pollers. For a poll loop, failing
/// fast and retrying is correct; blocking one for fifteen minutes would blind
/// every gate that reads it.
const WALLET_RESTORE_TIMEOUT: Duration = Duration::from_secs(900);

/// C47: the watch lane's read budget, sized so a cold chain-B watch COMPLETES.
///
/// The measured worst case is ~128s (open_wallet ~4s + full-scan refresh ~124s,
/// desk 2026-07-28), and the old budget was `DEFAULT_CALL_TIMEOUT` = 30s. A
/// watcher that gives up mid-restore does not cancel anything — the line
/// protocol cannot — it abandons an in-flight request, desyncs the pipe, and
/// the respawn re-runs the same restore into the same too-small budget. That
/// loop keeps the engine permanently mid-restore and answers nobody, which is
/// strictly worse than one slow poll. Watchers are background by definition:
/// they can afford to wait, and since C47a they wait holding no one's slot.
///
/// The trade, stated: while a cold watch holds the pipe, a protocol call queues
/// behind it for up to this long. That is the pre-warm argument (Start-Stack
/// opens both wallets before any drive), not a reason to re-shrink the budget —
/// shrinking recreates the thrash that starved the 2026-07-28 BUY lane.
const WATCH_CALL_TIMEOUT: Duration = Duration::from_secs(300);

const MOCK_T1_SLOT: i64 = 84_600_000;
const MOCK_T2_SLOT: i64 = 84_603_600;

fn mock_hex(parts: &[&str]) -> String {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(b"pwnda-desk-mock-v1");
    for p in parts {
        h.update(b"|");
        h.update(p.as_bytes());
    }
    hex::encode(h.finalize())
}

impl MockDeskCrypto {
    pub fn provenance(&self) -> KeyProvenance {
        KeyProvenance::Mock
    }

    /// Deterministic stand-ins. Mirrors the real provider's SHAPE exactly —
    /// including the role flips — so the state machine, persistence and gating
    /// are exercised identically; nothing it returns can move a coin.
    pub fn generate_swap_keys(
        &self,
        ctx: &SwapInitContext<'_>,
    ) -> Result<SwapKeyMaterial, CryptoError> {
        let (context_id, role, pair) = (ctx.swap_id, ctx.role, ctx.pair);
        if context_id.is_empty() {
            return Err(CryptoError::InvalidMaterial("empty context id".into()));
        }
        // The adaptor point + view key are the FOLLOWER's contribution. When the
        // client leads, the desk supplies both in M1 and the client must send
        // null - see the role flip in [[swap-desk-protocol]].
        let is_follower = role == ClientRole::Follower;
        Ok(SwapKeyMaterial {
            client_key_share_point: mock_hex(&[pair, context_id, "keyshare-point"]),
            client_chain_a_pubkey: mock_hex(&[pair, context_id, "chain-a-pubkey"]),
            adaptor_point: is_follower.then(|| mock_hex(&[pair, context_id, "adaptor-T"])),
            view_key: is_follower.then(|| mock_hex(&[pair, context_id, "view-key"])),
            // The mock drives the ADA leg, which has no cross-group proof in
            // either direction. Deliberately NOT a mock_hex: a placeholder here
            // would make every ADA fixture carry a proof and quietly satisfy
            // the leg-aware assertions that exist to refuse exactly that.
            dleq_proof: None,
            // No secret here: the mock has no sidecar, so its handle is just the
            // swap id. The real provider returns the engine's own `engineRef`.
            engine_ref: context_id.to_string(),
            // The OPPOSITE flip from the adaptor/view pair: the chain-A timelock
            // slots are LEADER material, so they are set only when we lead. A
            // leader echoes back whatever slots it was given, else the fixed
            // stand-ins; the real engine derives them from the live chain tip.
            t1_slot: (!is_follower).then(|| ctx.t1_slot.unwrap_or(MOCK_T1_SLOT)),
            t2_slot: (!is_follower).then(|| ctx.t2_slot.unwrap_or(MOCK_T2_SLOT)),
            provenance: KeyProvenance::Mock,
        })
    }

    /// Shape-only joint-key formation. Deterministic in both halves so the two
    /// sides of a mock swap agree, mirroring the real engine's property.
    pub fn ingest_counterparty(
        &self,
        swap_id: &str,
        cp: &CounterpartyKeys<'_>,
    ) -> Result<JointKeys, CryptoError> {
        if cp.key_share_point.len() != 64 || cp.chain_a_pubkey.len() != 64 {
            return Err(CryptoError::InvalidMaterial(
                "counterparty points must be 32-byte hex".into(),
            ));
        }
        Ok(JointKeys {
            chain_a_lock_addr: format!("addr_mock_{}", &mock_hex(&[swap_id, "lockA"])[..16]),
            chain_b_joint_key: mock_hex(&[swap_id, cp.key_share_point, "jointB"]),
            chain_b_joint_addr: format!("xmr_mock_{}", &mock_hex(&[swap_id, "jointBaddr"])[..16]),
        })
    }

    /// M3. Deferred to rung 2b for the vendored path: the real
    /// `exchange_refund_sigs` needs read-only chain access (the fee estimate
    /// fixes the canonical txid the pre-sig binds).
    pub fn presign_refund(
        &self,
        _material: &SwapKeyMaterial,
        ctx: &RefundSignContext<'_>,
    ) -> Result<wire::AdaptorPresig, CryptoError> {
        Ok(wire::AdaptorPresig {
            r_enc: mock_hex(&[ctx.swap_id, "refund-rEnc"]),
            sp: mock_hex(&[ctx.swap_id, "refund-sp"]),
        })
    }

    /// M3 verify. Same rung-2b deferral as [`Self::presign_refund`].
    pub fn verify_presig(
        &self,
        presig: &wire::AdaptorPresig,
        _ctx: &RefundSignContext<'_>,
    ) -> Result<(), CryptoError> {
        // Shape-only. A real provider verifies the adaptor equation and
        // subgroup-validates every incoming point (`valid_subgroup_point`).
        let ok = |s: &str| s.len() == 64 && s.chars().all(|c| c.is_ascii_hexdigit());
        if ok(&presig.r_enc) && ok(&presig.sp) {
            Ok(())
        } else {
            Err(CryptoError::InvalidMaterial(
                "presig fields must be 32-byte hex".into(),
            ))
        }
    }
}

// ─────────────────────── the vendored (real) provider ───────────────────────

/// The real engine, driven over the [`EngineSidecar`] stdio transport.
///
/// This holds NO crypto of its own — it marshals JSON to `desk_helper.py` and
/// back, which is exactly the "lift verbatim" contract: the same Python the desk
/// runs, with our role. Every operation here is one line-delimited round-trip.
pub struct VendoredDeskCrypto {
    sidecar: super::sidecar::EngineSidecar,
}

/// Pull a required string out of an engine result, naming the field when absent
/// so a protocol drift reads as "the engine did not send X", not "None".
fn req_str(v: &serde_json::Value, key: &str, method: &str) -> Result<String, CryptoError> {
    v.get(key)
        .and_then(|x| x.as_str())
        .map(str::to_string)
        .ok_or_else(|| {
            CryptoError::InvalidMaterial(format!("{method}: engine result is missing `{key}`"))
        })
}

fn opt_str(v: &serde_json::Value, key: &str) -> Option<String> {
    v.get(key).and_then(|x| x.as_str()).map(str::to_string)
}

fn opt_i64(v: &serde_json::Value, key: &str) -> Option<i64> {
    v.get(key).and_then(|x| x.as_i64())
}

impl VendoredDeskCrypto {
    pub fn new(sidecar: super::sidecar::EngineSidecar) -> Self {
        Self { sidecar }
    }

    /// `init_swap` — our M1/M2 public contribution. The SECRET stays in the
    /// sidecar's encrypted store; we get back only points plus the handle.
    ///
    /// Slots: when we FOLLOW we pass the desk's M1 slots straight through; when
    /// we LEAD we pass whatever the caller supplied (usually nothing) and the
    /// engine derives them from the live chain tip — which is why the
    /// unsupplied-leader path needs chain access. Either way we read the
    /// authoritative slots back OUT of the result, never off the desk's M1.
    pub async fn generate_swap_keys(
        &self,
        ctx: &SwapInitContext<'_>,
    ) -> Result<SwapKeyMaterial, CryptoError> {
        let mut params = serde_json::json!({
            "swapId": ctx.swap_id,
            "role": match ctx.role {
                ClientRole::Leader => "LEADER",
                ClientRole::Follower => "FOLLOWER",
            },
            "pair": ctx.pair,
            "amountA": ctx.amount_a,
            "amountB": ctx.amount_b,
            "t0": ctx.t0,
            "t1": ctx.t1,
            "t2": ctx.t2,
            "payoutAddress": ctx.payout_address,
            // D22. The engine derives the claim destination from who OWNS this
            // value, not from the reader's role — because the same engine code runs
            // on both sides and role cannot distinguish the two deployments.
            //
            // `false` because this is OUR payout address, not the counterparty's.
            // The desk's coordinator sends the counterparty's, so the field defaults
            // to `true` and its behaviour is unchanged. Omitting it here does not
            // fail quietly: the engine refuses init_swap outright ("payoutAddress is
            // owned by the LEADER, which is not us"), which is why this is a
            // one-line change and not a silent-corruption class.
            "payoutIsCounterparty": false,
            // D25's client half, and it is C12 again one field over.
            //
            // The desk made the refund destination nominatable and ownership-keyed,
            // exactly as it had already done for the payout. That fixes THEIR
            // derivation — and leaves ours deriving unless we send the same value,
            // which is precisely the shape that cost swap 46d85388: same engine,
            // same function, one input present on one side.
            //
            // Caught at M3 on the first drive after their fix landed: their refund
            // body paid our nominated address, ours paid the derived one, so the
            // pre-signature could not adaptor_verify. Nothing reached a chain.
            //
            // `false` because this is OUR refund address, not the counterparty's —
            // the mirror of the payout flag directly above.
            "refundAddress": ctx.refund_address,
            "refundIsCounterparty": false,
        });
        // Only send the slot keys when we actually have values: an explicit
        // null would be indistinguishable from "derive", and 0 is what v8 stopped
        // sending precisely because it is not a slot.
        if let (Some(o), Some(t1)) = (params.as_object_mut(), ctx.t1_slot) {
            o.insert("t1Slot".into(), t1.into());
        }
        if let (Some(o), Some(t2)) = (params.as_object_mut(), ctx.t2_slot) {
            o.insert("t2Slot".into(), t2.into());
        }
        // CLIENT-1 / C31-2. Sent UNCONDITIONALLY, unlike the slot keys above,
        // because absent and false are the same thing to the engine
        // (`bool(p.get("leaderProof"))` at desk_helper.py:518) while absent and
        // "derive it yourself" are different things for a slot. Sending it
        // always also means the engine's record and M1 can be compared after the
        // fact without knowing which client version opened the swap.
        if let Some(o) = params.as_object_mut() {
            o.insert("leaderProof".into(), ctx.leader_proof.into());
        }

        let r = self
            .sidecar
            .call("init_swap", params)
            .await
            .map_err(CryptoError::from)?;

        let is_follower = ctx.role == ClientRole::Follower;
        let material = SwapKeyMaterial {
            client_key_share_point: req_str(&r, "keySharePoint", "init_swap")?,
            client_chain_a_pubkey: req_str(&r, "chainAPubkey", "init_swap")?,
            adaptor_point: opt_str(&r, "adaptorPoint"),
            // CLIENT-1: present only when the engine was opened with the
            // leader-proof capability AND this leg has one. Absent is the
            // normal case and means "no proof", never "an empty proof".
            dleq_proof: opt_str(&r, "dleqProof"),
            view_key: opt_str(&r, "viewKey"),
            engine_ref: opt_str(&r, "engineRef").unwrap_or_else(|| ctx.swap_id.to_string()),
            // LEADER material. We take these from OUR OWN init_swap result (Q2),
            // never from the desk's M1 — when we lead, its M1 slots are null.
            t1_slot: (!is_follower).then(|| opt_i64(&r, "t1Slot")).flatten(),
            t2_slot: (!is_follower).then(|| opt_i64(&r, "t2Slot")).flatten(),
            provenance: KeyProvenance::Vendored,
        };

        // Fail closed on the role contract rather than sending a malformed M2.
        // These mirror the engine's own checks; catching them here names the
        // problem at the seam instead of as a rejected message.
        if is_follower {
            if material.adaptor_point.is_none() || material.view_key.is_none() {
                return Err(CryptoError::InvalidMaterial(
                    "init_swap(FOLLOWER) returned no adaptorPoint/viewKey - the follower must \
                     contribute both in M2"
                        .into(),
                ));
            }
        } else {
            match (material.t1_slot, material.t2_slot) {
                (Some(t1), Some(t2)) if t2 > t1 && t1 > 0 => {}
                _ => {
                    return Err(CryptoError::InvalidMaterial(format!(
                        "init_swap(LEADER) returned unusable timelock slots (t1={:?}, t2={:?}); \
                         the leader commits the chain-A refund window, so t2 > t1 > 0 is required",
                        material.t1_slot, material.t2_slot
                    )))
                }
            }
        }
        Ok(material)
    }

    /// `ingest_counterparty` — form the 2-of-2 joint key + the lock addresses.
    ///
    /// `ok:false` here is a torsion/small-order point or a wrong role shape. It
    /// is a theft-class rejection, so it surfaces as an error and is NEVER
    /// retried (the transport enforces that distinction too).
    pub async fn ingest_counterparty(
        &self,
        swap_id: &str,
        cp: &CounterpartyKeys<'_>,
    ) -> Result<JointKeys, CryptoError> {
        let mut params = serde_json::json!({
            "swapId": swap_id,
            "keySharePoint": cp.key_share_point,
            "chainAPubkey": cp.chain_a_pubkey,
            "adaptorPoint": cp.adaptor_point,
            "viewKey": cp.view_key,
            "dleqProof": cp.dleq_proof,
        });
        // The counterparty's slots, present only when THEY lead (we follow).
        if let (Some(o), Some(t1)) = (params.as_object_mut(), cp.t1_slot) {
            o.insert("t1Slot".into(), t1.into());
        }
        if let (Some(o), Some(t2)) = (params.as_object_mut(), cp.t2_slot) {
            o.insert("t2Slot".into(), t2.into());
        }

        let r = self
            .sidecar
            .call("ingest_counterparty", params)
            .await
            .map_err(CryptoError::from)?;

        // `ok:false` is a structured refusal WITH a reason, not an error frame.
        if r.get("ok").and_then(|v| v.as_bool()) != Some(true) {
            let reason = opt_str(&r, "reason").unwrap_or_else(|| "no reason given".into());
            return Err(CryptoError::InvalidMaterial(format!(
                "engine refused the counterparty material: {reason}"
            )));
        }
        Ok(JointKeys {
            chain_a_lock_addr: req_str(&r, "chainALockAddr", "ingest_counterparty")?,
            chain_b_joint_key: req_str(&r, "chainBJointKey", "ingest_counterparty")?,
            chain_b_joint_addr: req_str(&r, "chainBJointAddr", "ingest_counterparty")?,
        })
    }

    /// Record the realized chain-A lock UTxO. **Precondition for M3**: without
    /// it `exchange_refund_sigs` refuses (`no lock UTxO recorded yet`), because
    /// the refund body is built over this exact input.
    pub async fn set_lock_utxo(
        &self,
        swap_id: &str,
        txid: &str,
        index: i64,
        amount: &str,
    ) -> Result<(), CryptoError> {
        self.sidecar
            .call(
                "set_lock_utxo",
                serde_json::json!({
                    "swapId": swap_id, "txid": txid, "index": index, "amount": amount,
                }),
            )
            .await
            .map(|_| ())
            .map_err(CryptoError::from)
    }

    /// The chain-A destination OUR engine will build the claim body over.
    ///
    /// Read from the engine's own `status`, which since D20 derives it through the
    /// single `_claim_dest` used by the body builder itself — so what we read here
    /// is what we would sign, not a second derivation that could drift from it.
    ///
    /// Exists to be compared against the desk's published `claimDest` **before we
    /// lock chain B**. Empty means the engine has no view yet.
    pub async fn claim_dest(&self, swap_id: &str) -> Result<String, CryptoError> {
        let v = self
            .sidecar
            .call("status", serde_json::json!({ "swapId": swap_id }))
            .await
            .map_err(CryptoError::from)?;
        Ok(v.get("claimDest")
            .and_then(|d| d.as_str())
            .unwrap_or_default()
            .to_string())
    }

    /// The chain-A destination OUR engine will build the REFUND body to.
    ///
    /// Sibling of [`Self::claim_dest`], read the same way and for the same reason:
    /// what the body builder itself would use, not a second derivation that could
    /// drift from it. Empty means the engine has no view yet.
    pub async fn refund_dest(&self, swap_id: &str) -> Result<(String, String), CryptoError> {
        let v = self
            .sidecar
            .call("status", serde_json::json!({ "swapId": swap_id }))
            .await
            .map_err(CryptoError::from)?;
        let get = |k: &str| {
            v.get(k)
                .and_then(|d| d.as_str())
                .unwrap_or_default()
                .to_string()
        };
        Ok((get("refundDest"), get("refundDestSource")))
    }

    /// **LEADER, phase 1 of 2.** Build and sign our own chain-A lock, record its
    /// deterministic UTxO, and do **NOT** submit it. Returns the built output.
    ///
    /// This is the client half of prepare-and-share, mirrored for BUY_FOLLOWER
    /// (where we lead). The ordering it exists to make possible is:
    ///
    /// ```text
    ///   prepare_lock  ->  share the UTxO with the desk  ->  M3  ->  submit_lock
    /// ```
    ///
    /// and every step of that order is load-bearing. The desk-as-follower builds
    /// its refund pre-signature **over this exact input**, so it must learn the
    /// UTxO before M3; and we must hold its verified pre-signature before the
    /// lock goes on chain, or we would have funds locked in a script with no
    /// counter-signed way out. Submitting first and sharing after is the shape
    /// that strands a leg.
    ///
    /// Why a separate call rather than `lock`: the engine's `lock` RPC takes the
    /// leader branch straight through `prepare_and_lock_ada`, i.e. prepare AND
    /// submit in one round-trip, leaving no seam for the share and M3 in between.
    /// SELL never needed the split because there the DESK leads.
    ///
    /// Moves nothing. Idempotent — a second call returns the already-recorded
    /// UTxO rather than building a second transaction, which matters because a
    /// re-prepare could select different funding inputs and silently invalidate a
    /// pre-signature the counterparty is already holding (the desk's D17).
    ///
    /// Funding comes from the engine's own env (`ADA_FUNDING_SKEY_HEX`), not from
    /// a parameter — the client never handles the key.
    pub async fn prepare_lock(&self, swap_id: &str) -> Result<wire::LockUtxo, CryptoError> {
        // A generous budget rather than the 30s default: this builds and signs
        // against live protocol parameters over Blockfrost. Under-budgeting a
        // chain call is how C8 wedged a wallet-rpc for twenty minutes.
        let v = self
            .sidecar
            .call_with_timeout(
                "prepare_lock",
                serde_json::json!({ "swapId": swap_id }),
                WALLET_RESTORE_TIMEOUT,
            )
            .await
            .map_err(CryptoError::from)?;
        Ok(wire::LockUtxo {
            txid: req_str(&v, "txid", "prepare_lock")?,
            index: v.get("index").and_then(|i| i.as_i64()).ok_or_else(|| {
                CryptoError::Unavailable(
                    "prepare_lock returned no numeric `index`, so the prepared UTxO cannot be \
                     identified and M3 would bind the wrong input"
                        .into(),
                )
            })?,
            amount: v.get("amount").and_then(|a| a.as_i64()).ok_or_else(|| {
                CryptoError::Unavailable(
                    "prepare_lock returned no numeric `amount`, so the canonical refund body \
                     cannot be reconstructed"
                        .into(),
                )
            })?,
        })
    }

    /// **LEADER, phase 2 of 2.** Broadcast the lock prepared by [`Self::prepare_lock`].
    /// **This moves value.**
    ///
    /// Call it only once the counterparty's refund pre-signature has been
    /// received AND verified — before that, this puts funds into a script we
    /// cannot cooperatively exit.
    pub async fn submit_lock(&self, swap_id: &str) -> Result<String, CryptoError> {
        self.txid_call("submit_lock", swap_id).await
    }

    /// Publish the T1 refund. **This moves value** — it is the only method on
    /// this type that submits a transaction.
    ///
    /// The engine completes the refund from the pre-signature it stored at M3
    /// and broadcasts it, returning the txid. Publication is what reveals `s_a`
    /// on chain A, which is how the counterparty reclaims chain B (the desk's
    /// abort table, row 2) — so a refund that goes out is not a failure for
    /// either side, and one that silently does NOT go out is the worst outcome
    /// available. Hence: every error here is returned, never swallowed.
    pub async fn refund(&self, swap_id: &str) -> Result<String, CryptoError> {
        let v = self
            .sidecar
            .call("refund", serde_json::json!({ "swapId": swap_id }))
            .await
            .map_err(CryptoError::from)?;
        v.get("txid")
            .and_then(|t| t.as_str())
            .filter(|t| !t.is_empty())
            .map(str::to_string)
            .ok_or_else(|| {
                // A refund with no txid cannot be reported as broadcast: the
                // caller would mark the swap recovered and stop watching.
                CryptoError::Broadcast(format!(
                    "the engine accepted refund for swap {swap_id} but returned no txid, so \
                     there is nothing to confirm on chain - treating this as NOT broadcast"
                ))
            })
    }

    /// Recover the counterparty's revealed scalar from a claim or refund
    /// witness. Never returns the scalar itself — only whether the engine now
    /// holds it.
    ///
    /// The three-way `reason` is the point (A2). A `false` means one of three
    /// completely different things, and treating them alike either gives up on a
    /// recoverable coin or retries forever on one that is not:
    ///
    /// - `not-indexed` — the tx is not visible to the backend YET. Retry.
    /// - `unsupported-backend` — this backend can never do it. Permanent; a
    ///   human has to move.
    /// - `error:...` — transient. Retry.
    ///
    /// This is the same class distinction the transport preserves at the seam,
    /// applied to a chain read instead of an RPC.
    pub async fn extract_secret(
        &self,
        swap_id: &str,
        witness_txid: &str,
    ) -> Result<SecretExtraction, CryptoError> {
        let v = self
            .sidecar
            .call(
                "extract_secret",
                serde_json::json!({ "swapId": swap_id, "claimTxid": witness_txid }),
            )
            .await
            .map_err(CryptoError::from)?;
        Ok(SecretExtraction {
            secret_held: v
                .get("secretHeld")
                .and_then(serde_json::Value::as_bool)
                .unwrap_or(false),
            reason: v
                .get("reason")
                .and_then(|r| r.as_str())
                .unwrap_or_default()
                .to_string(),
        })
    }

    /// One poll of our OWN view of a lock. Raw report; the mapping onto the
    /// three states lives in [`super::observer`].
    ///
    /// C47a: WATCH lane — never queues on the pipe, yields to any pending
    /// protocol call. The observer already renders every transport error as
    /// COULD-NOT-LOOK, so a yielded round is a skipped poll, not a lie.
    pub async fn watch_lock(
        &self,
        swap_id: &str,
        chain: &str,
    ) -> Result<serde_json::Value, CryptoError> {
        self.sidecar
            .call_watch(
                "watch_lock",
                serde_json::json!({ "swapId": swap_id, "chain": chain }),
                WATCH_CALL_TIMEOUT,
            )
            .await
            .map_err(CryptoError::from)
    }

    /// Has the chain-A lock been SPENT, and by which transaction?
    ///
    /// This is what closes the refund-discovery gap (engine v11, shape 1): the
    /// follower finds the leader's refund itself instead of being told about it.
    /// A per-swap script address holds exactly one lock, so this is a two-tx
    /// history rather than a scan.
    ///
    /// Three states, never collapsed — same rule as `watch_lock`. A populated
    /// `error` means COULD NOT LOOK, which is emphatically not "not spent": read
    /// as the latter it would silence the very discovery this exists for.
    pub async fn watch_script_spend(&self, swap_id: &str) -> Result<SpendSighting, CryptoError> {
        // C47a: WATCH lane, same contract as `watch_lock` — the reclaim watch
        // treats every transport error as CouldNotLook-and-retry.
        let v = self
            .sidecar
            .call_watch(
                "watch_script_spend",
                serde_json::json!({ "swapId": swap_id }),
                WATCH_CALL_TIMEOUT,
            )
            .await
            .map_err(CryptoError::from)?;
        Ok(SpendSighting::from_engine(&v))
    }

    /// FOLLOWER reclaims chain B after the leader's refund leaked `s_a`.
    /// **Moves value.**
    /// `restore_height` is the Monero block to rebuild the joint wallet from.
    ///
    /// Optional, and the engine prefers it over anything in its own state (desk
    /// D18). It has to be passable because swaps recorded before the engine
    /// started storing `xmr_restore_height` have no usable height ANYWHERE — and
    /// the client cannot supply one by patching the state file, since `public` is
    /// covered by the D4 AAD. Without it the wallet restores from genesis: on
    /// stagenet that is ~2.17M blocks, which does not error, it just holds the
    /// single-threaded wallet-rpc for hours and starves every other caller.
    ///
    /// Too HIGH fails safe (the wallet never sees the output, the sweep finds
    /// nothing to spend); too low only costs scan time. So err high.
    pub async fn reclaim(
        &self,
        swap_id: &str,
        restore_height: Option<i64>,
    ) -> Result<String, CryptoError> {
        let mut params = serde_json::json!({ "swapId": swap_id });
        if let (Some(o), Some(h)) = (params.as_object_mut(), restore_height) {
            o.insert("restoreHeight".into(), serde_json::json!(h));
        }
        let v = self
            .sidecar
            .call_with_timeout("reclaim", params, WALLET_RESTORE_TIMEOUT)
            .await
            .map_err(CryptoError::from)?;
        v.get("txid")
            .and_then(|t| t.as_str())
            .filter(|t| !t.is_empty())
            .map(str::to_string)
            .ok_or_else(|| {
                CryptoError::Broadcast(format!(
                    "the engine accepted reclaim for swap {swap_id} but returned no txid, so \
                     there is nothing to confirm on chain - treating this as NOT reclaimed"
                ))
            })
    }

    // ── Rung-3 funded-choreography methods (consumed by the conductor) ──────
    //
    // Thin sidecar calls, added for the production driver. The safety ordering
    // that governs WHEN each may be called lives in `super::engine` (the gates)
    // and in the conductor; these are the downstream mechanism.

    /// Broadcast our lock: LEADER locks chain A (ADA), FOLLOWER locks chain B
    /// (XMR/ZEPH). **Moves value — the first irreversible on-chain step.**
    ///
    /// The caller MUST have passed the role-appropriate gate first. A FOLLOWER
    /// may call this ONLY after [`super::engine::safe_to_lock_follower`] confirms
    /// the LEADER's chain-A lock to depth — **observe A, then lock B**. Locking
    /// the scriptless coin before the scripted lock is confirmed is the
    /// directionality violation that strands funds; the gate is the precondition
    /// and this call is strictly downstream of it. (This is the exact inversion
    /// the desk caught in the driver design — encoded here so the method itself
    /// documents the ordering it depends on.)
    pub async fn lock(&self, swap_id: &str) -> Result<String, CryptoError> {
        self.txid_call("lock", swap_id).await
    }

    /// Complete and submit the cooperative CLAIM — the happy-path settlement,
    /// and **not** [`reclaim`](Self::reclaim). **Moves value.**
    ///
    /// `claim` completes the CLAIM adaptor pre-signature with the counterparty's
    /// revealed secret `t` to sweep the coin we are owed. `reclaim` completes the
    /// REFUND pre-signature with a leaked `s_a` after the counterparty aborts
    /// (abort-table row 2). Same crypto shape, opposite meaning — the desk caught
    /// this exact conflation in the design, so the happy path routes through
    /// `claim` and the abort path through `reclaim`, never the reverse.
    pub async fn claim(&self, swap_id: &str) -> Result<String, CryptoError> {
        self.txid_call("claim", swap_id).await
    }

    /// LEADER-only deep-abort escape after T2: sweep chain A alone when the
    /// counterparty is gone and even cooperative refund is unavailable (the
    /// `all[after T2, sigA]` branch). **Moves value.**
    pub async fn swipe(&self, swap_id: &str) -> Result<String, CryptoError> {
        self.txid_call("swipe", swap_id).await
    }

    /// Relay the counterparty's chain-B lock txid so a LEADER can run its own
    /// `watch_lock('B')` M5 gate against it — never trusting the desk's word for
    /// the lock it is about to gate on.
    pub async fn set_lock_b_txid(&self, swap_id: &str, txid: &str) -> Result<(), CryptoError> {
        self.sidecar
            .call(
                "set_lock_b_txid",
                serde_json::json!({ "swapId": swap_id, "txid": txid }),
            )
            .await
            .map(|_| ())
            .map_err(CryptoError::from)
    }

    /// FOLLOWER stores the LEADER's released claim adaptor pre-signature so
    /// [`claim`](Self::claim) can complete it with `t`. **The previously-missing
    /// caller of the M5 delivery.**
    ///
    /// The delivery mechanism mirrors by direction (the desk's answer to the
    /// design's open Q1): SELL_FOLLOWER polls `/status.releasedClaimSig` off the
    /// desk and feeds the released sig here; BUY_FOLLOWER is the LEADER and
    /// *releases* its own sig via `POST /ready-ack` instead, so it never ingests.
    /// This method is therefore the SELL side of the M5 wire.
    pub async fn ingest_claim_presig(
        &self,
        swap_id: &str,
        presig: &wire::AdaptorPresig,
    ) -> Result<(), CryptoError> {
        self.sidecar
            .call(
                "ingest_claim_presig",
                serde_json::json!({ "swapId": swap_id, "rEnc": presig.r_enc, "sp": presig.sp }),
            )
            .await
            .map(|_| ())
            .map_err(CryptoError::from)
    }

    /// Shared helper for the value-moving methods that return `{txid}`. A missing
    /// or empty txid is treated as NOT broadcast — reporting a submission that
    /// did not happen would mark the swap advanced and stop the watchers.
    async fn txid_call(&self, method: &'static str, swap_id: &str) -> Result<String, CryptoError> {
        // Value-moving calls get the wallet-restore budget: the leader's `claim`
        // sweeps chain B through the same restore+rescan path as `reclaim`, and a
        // generous ceiling costs a fast call nothing.
        let v = self
            .sidecar
            .call_with_timeout(
                method,
                serde_json::json!({ "swapId": swap_id }),
                WALLET_RESTORE_TIMEOUT,
            )
            .await
            .map_err(CryptoError::from)?;
        v.get("txid")
            .and_then(|t| t.as_str())
            .filter(|t| !t.is_empty())
            .map(str::to_string)
            .ok_or_else(|| {
                CryptoError::Broadcast(format!(
                    "the engine accepted {method} for swap {swap_id} but returned no txid, so \
                     there is nothing to confirm on chain - treating this as NOT submitted"
                ))
            })
    }

    /// M3. The FOLLOWER produces its refund pre-signature (`ours`); the LEADER
    /// verifies the follower's under output-pinning (`verified`).
    ///
    /// **Needs read-only chain access**, and this is the subtle part: the
    /// canonical refund body's fee comes from live protocol parameters, so both
    /// parties must estimate against the SAME current params or they build
    /// different bodies, the txids differ, and the pre-signature "disagrees"
    /// when nothing is actually wrong. That failure is fail-closed (it blocks,
    /// it does not strand) but it is the one to recognise on sight.
    pub async fn exchange_refund_sigs(
        &self,
        swap_id: &str,
        counterparty: Option<&wire::AdaptorPresig>,
        counterparty_leg_sigs: Option<&wire::LegSigs>,
    ) -> Result<RefundSigExchange, CryptoError> {
        let mut params = serde_json::json!({ "swapId": swap_id });
        if let (Some(o), Some(cp)) = (params.as_object_mut(), counterparty) {
            o.insert(
                "counterpartyPresig".into(),
                serde_json::json!({ "rEnc": cp.r_enc, "sp": cp.sp }),
            );
        }
        // CC-23: the LTC leg's counterparty half. The engine reads these as
        // `refundParentSig` / `refundSpendSig` (desk_helper.py:913-914). Absent
        // on ADA, where the whole concept does not exist.
        if let (Some(o), Some(ls)) = (params.as_object_mut(), counterparty_leg_sigs) {
            o.insert(
                "refundParentSig".into(),
                serde_json::json!(ls.refund_parent_sig),
            );
            o.insert(
                "refundSpendSig".into(),
                serde_json::json!(ls.refund_spend_sig),
            );
        }
        let r = self
            .sidecar
            .call("exchange_refund_sigs", params)
            .await
            .map_err(CryptoError::from)?;

        let ours = match r.get("ours") {
            Some(v) if !v.is_null() => Some(wire::AdaptorPresig {
                r_enc: req_str(v, "rEnc", "exchange_refund_sigs")?,
                sp: req_str(v, "sp", "exchange_refund_sigs")?,
            }),
            _ => None,
        };
        // CC-23: our own pair, when this leg has one. The engine returns it
        // under `legSigs` (desk_helper.py:963). Absent on ADA, and absent from
        // an engine that predates the field - which is "this leg has no leg
        // sigs", not "the leg sigs were empty".
        let ours_leg = r.get("legSigs").and_then(|v| {
            let p = v.get("refundParentSig")?.as_str()?.trim();
            let sp = v.get("refundSpendSig")?.as_str()?.trim();
            if p.is_empty() || sp.is_empty() {
                return None;
            }
            Some(wire::LegSigs {
                refund_parent_sig: p.to_string(),
                refund_spend_sig: sp.to_string(),
            })
        });
        Ok(RefundSigExchange {
            ours,
            ours_leg_sigs: ours_leg,
            verified: r.get("verified").and_then(|v| v.as_bool()).unwrap_or(false),
            // Engine 6e5194b returns the refund txid derived by the engine running
            // this call — which on the leader path is OURS. Empty from the follower
            // path and from any pre-6e5194b engine; absence means "not derived here",
            // never "agreed".
            our_refund_txid: r
                .get("refundTxid")
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .to_string(),
        })
    }

    /// M5, the setReady gate. The LEADER releases its claim adaptor pre-sig ONLY
    /// after the engine's own chain-B watch AND `chain_b_confirmed` both agree.
    ///
    /// The engine gate is fail-closed, but it is the INNER belt: our own
    /// `engine::safe_to_release_claim_sig` must already have said yes before we
    /// call this. Never pass `true` on the desk's word — that is the H1
    /// setReady-timing theft.
    pub async fn release_claim_sig(
        &self,
        swap_id: &str,
        chain_b_confirmed: bool,
    ) -> Result<wire::AdaptorPresig, CryptoError> {
        let r = self
            .sidecar
            .call(
                "release_claim_sig",
                serde_json::json!({ "swapId": swap_id, "chainBConfirmed": chain_b_confirmed }),
            )
            .await
            .map_err(CryptoError::from)?;
        Ok(wire::AdaptorPresig {
            r_enc: req_str(&r, "rEnc", "release_claim_sig")?,
            sp: req_str(&r, "sp", "release_claim_sig")?,
        })
    }

    /// A liveness round-trip: spawn the sidecar (if not already) and verify it
    /// answers `ping` with `pong:true`. Called at ARM TIME (the desk's endorsed
    /// ping-on-arm) so a config fault — a bad interpreter, a missing engine dir,
    /// the exit-78 startup fault — surfaces THEN, at startup, rather than on the
    /// first funds-moving call. Returns the engine's reported preset (`env`).
    pub async fn ping(&self) -> Result<String, CryptoError> {
        let v = self
            .sidecar
            .call("ping", serde_json::json!({}))
            .await
            .map_err(CryptoError::from)?;
        if v.get("pong").and_then(serde_json::Value::as_bool) != Some(true) {
            return Err(CryptoError::Unavailable(format!(
                "engine ping did not answer pong:true (got {v})"
            )));
        }
        Ok(v.get("env").and_then(|e| e.as_str()).unwrap_or_default().to_string())
    }

    /// Stop the child cleanly (drop stdin -> EOF -> exit 0, PID-kill only if it
    /// lingers).
    pub async fn shutdown(&self) {
        self.sidecar.shutdown().await;
    }
}

/// The M3 exchange result. A FOLLOWER gets `ours` populated and `verified: true`
/// trivially (it produced, it did not verify); a LEADER gets `ours: None` and a
/// meaningful `verified`.
#[derive(Debug, Clone, PartialEq)]
pub struct RefundSigExchange {
    pub ours: Option<wire::AdaptorPresig>,
    /// CC-23: our half of the LTC leg's signature pair, when this leg has one.
    ///
    /// `None` on ADA and from an engine predating the field. That is "this leg
    /// has no leg sigs", never "the leg sigs were empty" - the conductor turns
    /// the second into a refusal rather than sending a half-populated M3.
    pub ours_leg_sigs: Option<wire::LegSigs>,
    pub verified: bool,
    /// The refund txid **our own** engine derived for this body (engine 6e5194b),
    /// on the leader path only — empty from the follower path and from any older
    /// engine, where absence means "not derived here", never "agreed".
    ///
    /// Surfaced in the M3 failure because a bare `verified=false` cannot
    /// distinguish a wrong body from a wrong UTxO from a bad signature. The desk's
    /// counterpart is NOT on the wire — `wire::RefundSigsResponse` carries no
    /// txid — so this is half a diff: it gives the operator a concrete value to
    /// relay rather than a boolean to argue about.
    pub our_refund_txid: String,
}

/// The Stage-A refund broadcaster: refuses, loudly and specifically.
///
/// It exists so the refund PATH is real and exercised — the watcher fires, the
/// record is loaded, the pre-signature is pulled out, and a broadcaster is
/// called with a fully-assembled request. Only the final chain submission is
/// absent, and its absence is reported rather than silently skipped.
pub struct UnavailableRefundBroadcaster;

impl RefundBroadcaster for UnavailableRefundBroadcaster {
    fn broadcast_refund<'a>(&'a self, req: &'a RefundRequest<'a>) -> BroadcastFuture<'a> {
        Box::pin(async move {
            // Mock material is refused FIRST: it is the more dangerous case,
            // because a real broadcaster handed mock pre-signatures would
            // publish garbage.
            if !req.provenance.is_real() {
                return Err(CryptoError::MockMaterialRefused);
            }
            Err(CryptoError::Unavailable(format!(
                "no refund broadcaster is wired for pair {} chain {} (swap {}). The vendored \
                 engine library supplies the chain-leg transaction builders; until it is \
                 present the pre-signed refund stays on disk and must be published manually.",
                req.pair, req.chain, req.swap_id
            )))
        })
    }
}

/// The REAL broadcaster: publishes through our OWN engine sidecar's `refund`.
///
/// It does not assemble a transaction. The engine holds the pre-signature and
/// the chain-leg builders, so this addresses the swap by id and lets the engine
/// complete the refund it already has — the same reason the crypto is not
/// re-implemented here. The client-side guards in
/// [`super::refund::execute_refund`] still run first, and they read the CLIENT's
/// persisted record rather than the engine's, so the two have to agree before
/// anything is published.
pub struct SidecarRefundBroadcaster;

impl RefundBroadcaster for SidecarRefundBroadcaster {
    fn broadcast_refund<'a>(&'a self, req: &'a RefundRequest<'a>) -> BroadcastFuture<'a> {
        Box::pin(async move {
            // Same ordering as the unavailable path — mock material is refused
            // before anything touches a chain. This is the one broadcaster that
            // CAN move value, so it is where the check earns its keep.
            if !req.provenance.is_real() {
                return Err(CryptoError::MockMaterialRefused);
            }
            let ActiveCrypto::Vendored(v) = active_crypto() else {
                return Err(CryptoError::Unavailable(
                    "the sidecar refund broadcaster was selected but no vendored engine is \
                     installed - refusing to report a refund as broadcast when nothing could \
                     have published it"
                        .into(),
                ));
            };
            v.refund(req.swap_id).await
        })
    }
}

/// The active crypto provider.
///
/// THE SWAP-IN POINT: return the vendored-library provider here and the whole
/// desk tier picks it up. Everything upstream is already written against the
/// trait.
pub fn active_crypto() -> &'static ActiveCrypto {
    ACTIVE.get_or_init(|| ActiveCrypto::Mock(MockDeskCrypto))
}

static ACTIVE: std::sync::OnceLock<ActiveCrypto> = std::sync::OnceLock::new();

/// THE SWAP-IN POINT. Install the vendored engine once, at startup, when the
/// interpreter + engine dir are configured. Returns `Err` if a provider is
/// already installed — a swap must never change providers mid-flight, and a
/// silent second install would make `provenance` a lie for swaps already
/// accepted under the first one.
pub fn install_vendored(sidecar: super::sidecar::EngineSidecar) -> Result<(), CryptoError> {
    ACTIVE
        .set(ActiveCrypto::Vendored(VendoredDeskCrypto::new(sidecar)))
        .map_err(|_| {
            CryptoError::Unavailable(
                "a crypto provider is already installed; the engine cannot be swapped in after \
                 the first swap has used one"
                    .into(),
            )
        })
}

/// The active refund broadcaster. Same swap-in story as [`active_crypto`].
pub fn active_refund_broadcaster() -> &'static dyn RefundBroadcaster {
    // Follows whatever crypto provider is installed rather than being switched
    // separately. Two independent switches is how a build ends up verifying
    // against a real engine while broadcasting through a stub — or, worse, the
    // reverse.
    match active_crypto() {
        ActiveCrypto::Vendored(_) => &SidecarRefundBroadcaster,
        ActiveCrypto::Mock(_) => &UnavailableRefundBroadcaster,
    }
}

/// True when BOTH halves of the seam are real. The accept path logs on this so
/// a build running placeholders can never look like a build that is not.
pub fn crypto_is_production_ready() -> bool {
    active_crypto().provenance().is_real()
}


    #[tokio::test]
    async fn live_sell_follower_offline_half_agrees() {
        let (Some(us), Some(desk)) = (live_provider("sell-us"), live_provider("sell-desk")) else {
            eprintln!("skipping: set PWNDA_ENGINE_TEST_PYTHON + PWNDA_ENGINE_TEST_DIR");
            return;
        };
        let id = "seam_sell_1";

        // The DESK leads and commits the slots (its M1).
        let desk_m1 = desk
            .generate_swap_keys(&init_ctx(id, ClientRole::Leader, Some(T1), Some(T2)))
            .await
            .expect("desk init_swap(LEADER)");
        assert_eq!(desk_m1.t1_slot, Some(T1), "the leader commits the slots");

        // WE follow: we contribute the adaptor point + view key, no slots.
        let ours = us
            .generate_swap_keys(&init_ctx(id, ClientRole::Follower, Some(T1), Some(T2)))
            .await
            .expect("our init_swap(FOLLOWER)");
        assert!(ours.adaptor_point.is_some() && ours.view_key.is_some());
        assert_eq!(ours.t1_slot, None, "a follower must not commit slots");
        // The same-curve invariant the desk enforces on our M2.
        assert_eq!(ours.adaptor_point, Some(ours.client_key_share_point.clone()));
        // And the M2 we would actually send carries null slots.
        assert_eq!(ours.keys_request().t1_slot, None);

        // Each side ingests the other's half. We pass the desk's slots (it leads).
        let our_joint = us
            .ingest_counterparty(id, &cp_from(&desk_m1, Some(T1), Some(T2)))
            .await
            .expect("we ingest the desk M1");
        let desk_joint = desk
            .ingest_counterparty(id, &cp_from(&ours, None, None))
            .await
            .expect("desk ingests our M2");

        assert_eq!(
            our_joint, desk_joint,
            "both sides must derive the SAME joint key + lock addresses"
        );
        assert!(our_joint.chain_a_lock_addr.starts_with("addr"));
        us.shutdown().await;
        desk.shutdown().await;
    }

    #[tokio::test]
    async fn live_buy_follower_offline_half_agrees() {
        let (Some(us), Some(desk)) = (live_provider("buy-us"), live_provider("buy-desk")) else {
            eprintln!("skipping: engine test env not set");
            return;
        };
        let id = "seam_buy_1";

        // WE lead: we commit the chain-A refund window.
        let ours = us
            .generate_swap_keys(&init_ctx(id, ClientRole::Leader, Some(T1), Some(T2)))
            .await
            .expect("our init_swap(LEADER)");
        assert_eq!(ours.t1_slot, Some(T1));
        assert!(ours.adaptor_point.is_none(), "a leader sends no adaptor point");
        // The M2 we send carries the slots - this is the v7 co-implement.
        assert_eq!(ours.keys_request().t1_slot, Some(T1));

        // The DESK follows, and inits with slots UNRESOLVED - the path v8 fixed.
        let desk_m1 = desk
            .generate_swap_keys(&init_ctx(id, ClientRole::Follower, None, None))
            .await
            .expect("desk init_swap(FOLLOWER) with deferred slots - broken before v8");
        assert!(desk_m1.adaptor_point.is_some(), "the follower contributes T");

        // We ingest the desk's half (no slots - it follows); the desk ingests
        // ours WITH our committed slots, which is how it reaches our address.
        let our_joint = us
            .ingest_counterparty(id, &cp_from(&desk_m1, None, None))
            .await
            .expect("we ingest the desk material");
        let desk_joint = desk
            .ingest_counterparty(id, &cp_from(&ours, Some(T1), Some(T2)))
            .await
            .expect("desk ingests our M2 slots");

        assert_eq!(
            our_joint, desk_joint,
            "the desk must reach OUR chain-A address from the slots we committed"
        );
        us.shutdown().await;
        desk.shutdown().await;
    }

    /// Build the counterparty view of a party's own material.
